(* ====================================================================== *)
(* ToyC 编译器公共定义                                                    *)
(* AST 与 CFG 共享的类型                                                  *)
(* ====================================================================== *)

(* ---------------------------------------------------------------------- *)
(* 类型                                                                   *)
(* ---------------------------------------------------------------------- *)

(* "int" | "void" *)
type typ = Int | Void

(* ---------------------------------------------------------------------- *)
(* 运算符                                                                 *)
(* ---------------------------------------------------------------------- *)

(* 二元运算符 *)
type binary_op =
  | LOr   (* || *)
  | LAnd  (* && *)
  | Eq    (* == *)
  | Ne    (* != *)
  | Lt    (* <  *)
  | Gt    (* >  *)
  | Le    (* <= *)
  | Ge    (* >= *)
  | Add   (* +  *)
  | Sub   (* -  *)
  | Mul   (* *  *)
  | Div   (* /  *)
  | Mod   (* %  *)

(* 一元运算符 *)
type unary_op =
  | Pos  (* + *)
  | Neg  (* - *)
  | Not  (* ! *)

(* ---------------------------------------------------------------------- *)
(* 源码位置                                                               *)
(* ---------------------------------------------------------------------- *)

type loc = Lexing.position * Lexing.position

let string_of_loc ((sp, ep) : loc) : string =
  let line = sp.Lexing.pos_lnum in
  let col1 = sp.Lexing.pos_cnum - sp.Lexing.pos_bol + 1 in
  let col2 = ep.Lexing.pos_cnum - ep.Lexing.pos_bol + 1 in
  if line = ep.Lexing.pos_lnum then
    Printf.sprintf "%d:%d-%d" line col1 col2
  else
    Printf.sprintf "%d:%d-%d:%d" line col1 ep.Lexing.pos_lnum col2

(* 带位置的 AST 节点包装 *)
type 'a located = {
  node : 'a;
  loc  : loc;
}

(* ---------------------------------------------------------------------- *)
(* 32 位有符号截断                                                       *)
(*                                                                        *)
(* ToyC 的 int 是 32 位有符号整数（要求.md），RISC-V rv32 的算术按 32 位  *)
(* 回绕。但 OCaml 的 int 是 63 位，编译期做常量折叠/求值时必须显式模拟    *)
(* 这个 wraparound，否则溢出的常量会被误当作 64 位值参与后续比较。        *)
(* ---------------------------------------------------------------------- *)

let wrap32 (x : int) : int =
  let x = x land 0xFFFFFFFF in
  if x land 0x80000000 <> 0 then x - 0x100000000 else x
